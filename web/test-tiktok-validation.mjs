import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
import { createRequire } from "node:module";
import ts from "typescript";
const source=fs.readFileSync(new URL("./features/posts/utils/tiktok-validator.ts",import.meta.url),"utf8");
const compiled=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const exports={};
vm.runInThisContext(`(function(require,exports){${compiled}\n})`)(createRequire(import.meta.url),exports);
const { emptyTikTokOptions, effectiveTikTokOptions, validateTikTokPost }=exports;
const creator={privacy_level_options:["SELF_ONLY","PUBLIC_TO_EVERYONE"],max_video_post_duration_sec:60,comment_disabled:true};
const options={...emptyTikTokOptions,privacy_level:"SELF_ONLY",consent:true};
const media=[{contentType:"video/mp4",complete:true,size:1000}];
const meta={duration:20,width:1080,height:1920};
assert.equal(validateTikTokPost(options,creator,media,meta,"caption"),null);
assert.match(validateTikTokPost({...options,privacy_level:"FRIENDS"},creator,media,meta,""),/privacy/);
assert.match(validateTikTokPost(options,creator,[],meta,""),/one completed video/);
assert.match(validateTikTokPost(options,creator,media,{...meta,duration:61},""),/duration/);
assert.match(validateTikTokPost(options,creator,media,meta,"😀".repeat(1101)),/2200/);
assert.match(validateTikTokPost({...options,consent:false},creator,media,meta,""),/Confirm/);
assert.match(validateTikTokPost({...options,brand_content_toggle:true},creator,media,meta,""),/private/);
assert.match(validateTikTokPost({...options,commercial_content:true},creator,media,meta,""),/Choose/);
assert.equal(effectiveTikTokOptions({...options,disable_comment:false},creator).disable_comment,true);
assert.match(validateTikTokPost(options,undefined,media,meta,""),/Load current/);
console.log("TikTok validation: 10 checks passed (shared by publish-now and scheduling).");
